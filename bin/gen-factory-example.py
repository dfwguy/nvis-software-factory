"""Generate factory.toml.example from the settings registry.

Author: Rafael M. Koike & Cursor Agent ("Ada")

The example file and the code that reads it drift the moment they are maintained separately, and
the drift is invisible: the file looks authoritative, so somebody copies a setting that no longer
exists and wonders why it does nothing. Generating it from the registry makes that impossible, and
``--check`` in CI makes forgetting to regenerate impossible too.

Usage:
    bin/gen-factory-example.py            # write the file
    bin/gen-factory-example.py --check    # exit non-zero if the committed file is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "backend"))

import config_registry  # noqa: E402  (path must be set first)

OUTPUT = REPO_ROOT / "factory.toml.example"

PREAMBLE = '''\
# NVIS Software Factory — configuration (EXAMPLE)
#
# GENERATED by bin/gen-factory-example.py from backend/config_registry.py. Do not hand-edit: add or
# change the declaration and regenerate, or this file drifts from the code that reads it. CI runs
# `bin/gen-factory-example.py --check` and fails on a stale copy.
#
# HOW TO USE
#   cp factory.toml.example factory.toml
#   $EDITOR factory.toml
#
# Every value here can also be set as an environment variable — the name is shown above each entry.
# The ENVIRONMENT WINS: this file is a baseline, applied with setdefault semantics at launch, so a
# container can be configured by compose without the file needing to know.
#
# SECRETS ARE REFUSED FROM THIS FILE. Settings marked secret in the registry are rejected at
# startup if they appear here, and the process exits rather than warning. Config files get
# committed; that is the whole reason. Supply them as environment variables or through a mounted
# secret file. They are listed at the bottom for reference.
#
# Values shown are the DEFAULTS. Commented-out lines are settings with no default, which you must
# supply — the application will not start without the ones marked REQUIRED.
'''


def _render_value(setting: config_registry.Setting) -> str:
    """TOML literal for a default. Types matter: a quoted integer is a different value."""
    default = setting.default
    if default is None:
        return ""
    if setting.type == "bool":
        return "true" if default.lower() in {"1", "true", "yes", "on"} else "false"
    if setting.type in {"int", "float"}:
        return default
    return f'"{default}"'


def _wrap(text: str, width: int = 96, prefix: str = "# ") -> list[str]:
    words = text.split()
    lines: list[str] = []
    current = prefix
    for word in words:
        if len(current) + len(word) + 1 > width and current != prefix:
            lines.append(current.rstrip())
            current = prefix
        current += word + " "
    if current.strip() != prefix.strip():
        lines.append(current.rstrip())
    return lines


def render() -> str:
    out: list[str] = [PREAMBLE]
    secrets: list[config_registry.Setting] = []

    for section in config_registry.sections():
        entries = [s for s in config_registry.all_settings() if s.section == section]
        visible = [s for s in entries if not s.secret]
        secrets.extend(s for s in entries if s.secret)
        if not visible:
            continue

        out.append("")
        out.append(f"[{section}]")

        for setting in visible:
            out.append("")
            out.extend(_wrap(setting.description))
            if setting.choices:
                out.append(f"# One of: {', '.join(setting.choices)}")
            if setting.note:
                out.extend(_wrap(setting.note))
            marker = "  REQUIRED" if setting.is_required() else ""
            out.append(f"# env: {setting.env}{marker}")
            value = _render_value(setting)
            if value:
                out.append(f"{setting.key} = {value}")
            else:
                out.append(f"# {setting.key} =")

    if secrets:
        out.append("")
        out.append("# " + "─" * 76)
        out.append("# SECRETS — set these in the environment, NOT in this file.")
        out.append("# Listed here so the full configuration surface is discoverable in one place.")
        out.append("# " + "─" * 76)
        for setting in sorted(secrets, key=lambda s: s.env):
            out.append("#")
            out.extend(_wrap(setting.description, prefix="#   "))
            marker = "  REQUIRED" if setting.is_required() else ""
            out.append(f"#   export {setting.env}=...{marker}")

    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="exit non-zero if the committed file differs from what would be "
                             "generated")
    args = parser.parse_args(argv[1:])

    rendered = render()

    if args.check:
        if not OUTPUT.is_file():
            print(f"gen-factory-example: FAIL — {OUTPUT.name} does not exist. "
                  "Run bin/gen-factory-example.py and commit it.", file=sys.stderr)
            return 1
        current = OUTPUT.read_text(encoding="utf-8")
        if current != rendered:
            print(f"gen-factory-example: FAIL — {OUTPUT.name} is stale. "
                  "A setting was added or changed without regenerating it.\n"
                  "  Run: python bin/gen-factory-example.py", file=sys.stderr)
            return 1
        count = len(config_registry.all_settings())
        print(f"gen-factory-example: PASS — {OUTPUT.name} matches {count} declared settings")
        return 0

    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"gen-factory-example: wrote {OUTPUT.relative_to(REPO_ROOT)} "
          f"({len(config_registry.all_settings())} settings)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
