"""Numbered SQL migrations, applied at startup.

Author: Rafael M. Koike & Cursor Agent ("Ada")

Durability criterion D4. A migration an operator has to remember to run is a migration that gets
skipped, so this runs from the composition root on every boot and is a no-op when there is nothing
to do.

Migrations are **plain .sql files**, numbered, in ``store/migrations/``. Not a Python DSL and not
an ORM's autogenerated diff, for one reason: when something has gone wrong with a production
database at an unhelpful hour, the person fixing it needs to be able to read what was applied and
apply the next one by hand from a ``sqlite3`` prompt. A DSL puts a layer of indirection between
them and that.

CHECKSUMS
---------
Each applied migration's SHA-256 is recorded. If a file changes after it has been applied, startup
refuses rather than continuing: the database no longer matches the migration history, and every
subsequent migration was written against an assumption that is now false. The fix is a new
migration, never an edit to an old one.

Each file runs inside a transaction, so a failure part-way leaves the previous schema rather than
half the new one. SQLite supports transactional DDL, which is what makes this possible at all --
several other engines do not.
"""

from __future__ import annotations

import hashlib
import logging
import re
import sqlite3
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

from . import db

_logger = logging.getLogger("nvsf.store.migrations")

MIGRATIONS_DIR = Path(__file__).resolve().parent / "migrations"

_NAME_RE = re.compile(r"^(\d{4})_([a-z0-9_]+)\.sql$")

_BOOTSTRAP = """
CREATE TABLE IF NOT EXISTS schema_migrations (
    version     INTEGER PRIMARY KEY,
    name        TEXT NOT NULL,
    checksum    TEXT NOT NULL,
    applied_at  TEXT NOT NULL
)
"""


class MigrationError(RuntimeError):
    """The migration history and the files on disk disagree, or a migration failed."""


@dataclass(frozen=True)
class Migration:
    version: int
    name: str
    path: Path
    sql: str

    @property
    def checksum(self) -> str:
        return hashlib.sha256(self.sql.encode("utf-8")).hexdigest()


def discover() -> list[Migration]:
    """Every migration file, in version order.

    A filename that does not match ``NNNN_name.sql`` is an error rather than something to skip: a
    typo'd filename would otherwise mean a migration that silently never runs, and the resulting
    "column does not exist" appears somewhere unrelated.
    """
    found: list[Migration] = []
    seen: dict[int, str] = {}
    for path in sorted(MIGRATIONS_DIR.glob("*.sql")):
        match = _NAME_RE.match(path.name)
        if not match:
            raise MigrationError(
                f"{path.name} does not match NNNN_name.sql (four digits, lowercase, underscores). "
                "A file the runner cannot parse would silently never be applied."
            )
        version = int(match.group(1))
        if version in seen:
            raise MigrationError(
                f"two migrations share version {version:04d}: {seen[version]} and {path.name}. "
                "Order would depend on the filesystem; renumber one."
            )
        seen[version] = path.name
        found.append(Migration(
            version=version,
            name=match.group(2),
            path=path,
            sql=path.read_text(encoding="utf-8"),
        ))
    return found


def applied(conn: sqlite3.Connection) -> dict[int, tuple[str, str]]:
    """``{version: (name, checksum)}`` for what the database says has been applied."""
    conn.execute(_BOOTSTRAP)
    return {
        int(row["version"]): (row["name"], row["checksum"])
        for row in conn.execute("SELECT version, name, checksum FROM schema_migrations")
    }


def pending(conn: sqlite3.Connection | None = None) -> list[Migration]:
    """Migrations not yet applied. Verifies the checksums of those that have been."""
    conn = conn or db.connection()
    done = applied(conn)
    result: list[Migration] = []
    for migration in discover():
        record = done.get(migration.version)
        if record is None:
            result.append(migration)
            continue
        _, checksum = record
        if checksum != migration.checksum:
            raise MigrationError(
                f"migration {migration.version:04d}_{migration.name}.sql has changed since it was "
                f"applied (recorded {checksum[:12]}, file {migration.checksum[:12]}).\n"
                "An applied migration is history and cannot be edited -- every migration after it "
                "was written against the schema it produced. Write a new migration instead.\n"
                "If this is a development database you are willing to lose, delete it and let the "
                "history rebuild."
            )
    return result


def _transactional_script(migration: Migration) -> str:
    """The migration plus its bookkeeping row, wrapped in one transaction.

    The transaction has to be inside the script text rather than around the ``executescript`` call:
    ``executescript`` commits any transaction already in progress before it runs, so an outer
    ``BEGIN`` is silently discarded and the DDL ends up autocommitted statement by statement. That
    is a genuinely nasty failure mode -- a migration that fails half way would leave half a schema
    behind, and the runner would report a clean rollback.

    The bookkeeping INSERT is inlined rather than parameterized because ``executescript`` takes no
    parameters. Every value is safe by construction, not by escaping: ``version`` is an int parsed
    from four digits, ``name`` matched ``[a-z0-9_]+`` in :func:`discover`, ``checksum`` is
    hex from SHA-256, and the timestamp is generated here. None of it is input.
    """
    applied_at = datetime.now(UTC).isoformat(timespec="seconds")
    return (
        "BEGIN IMMEDIATE;\n"
        f"{migration.sql}\n"
        "INSERT INTO schema_migrations (version, name, checksum, applied_at) VALUES "
        f"({migration.version}, '{migration.name}', '{migration.checksum}', '{applied_at}');\n"
        "COMMIT;\n"
    )


def apply(conn: sqlite3.Connection | None = None) -> list[str]:
    """Apply pending migrations. Returns what was applied, for logging and tests.

    Serialized by a lock: gunicorn starts threads that could otherwise both reach this on a cold
    boot, and two concurrent CREATE TABLE statements produce a confusing error rather than a clear
    one.
    """
    with db._schema_lock:
        target = conn or db.connection()
        outstanding = pending(target)
        if not outstanding:
            return []

        names: list[str] = []
        for migration in outstanding:
            label = f"{migration.version:04d}_{migration.name}"
            _logger.info("store: applying migration %s", label)
            try:
                target.executescript(_transactional_script(migration))
            except sqlite3.Error as exc:
                # The script's own COMMIT never ran, so the transaction is still open. Close it
                # explicitly rather than leaving the connection holding a write lock.
                if target.in_transaction:
                    target.execute("ROLLBACK")
                raise MigrationError(
                    f"migration {label} failed and was rolled back: {exc}. The schema is "
                    "unchanged."
                ) from exc
            names.append(label)

        _logger.info("store: applied %d migration(s)", len(names))
        return names


def current_version(conn: sqlite3.Connection | None = None) -> int:
    """Highest applied version, or 0. Reported by the health endpoint."""
    target = conn or db.connection()
    row = target.execute(
        "SELECT COALESCE(MAX(version), 0) AS v FROM schema_migrations"
    ).fetchone() if _has_table(target) else None
    return int(row["v"]) if row else 0


def _has_table(conn: sqlite3.Connection) -> bool:
    return conn.execute(
        "SELECT 1 FROM sqlite_master WHERE type='table' AND name='schema_migrations'"
    ).fetchone() is not None
