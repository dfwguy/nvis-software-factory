def describe(setting: Setting, value: str | None) -> str:
    """Render a value for logs and diagnostics. Secrets report shape, never content."""
    if value is None:
        return "<unset>"
    if setting.secret:
        return f"<set, {len(value)} chars>"
    return value


def missing_required() -> list[Setting]:
    """Declared-required settings with no value in the environment.

    Called by the startup gate, which reports all of them at once. Reporting one per restart turns
    a five-minute configuration task into an afternoon.
    """
    return [
        s for s in all_settings()
        if s.is_required() and not os.environ.get(s.env)
    ]


def invalid_choices() -> list[tuple[Setting, str]]:
    """Settings whose value is outside their declared ``choices``."""
    bad: list[tuple[Setting, str]] = []
    for setting in all_settings():
        if not setting.choices:
            continue
        value = os.environ.get(setting.env)
        if value and value not in setting.choices:
            bad.append((setting, value))
    return bad


def as_dict() -> dict[str, Any]:
    """Resolved configuration for the diagnostics endpoint. Secrets are described, not disclosed."""
    return {
        s.env: describe(s, os.environ.get(s.env) or s.default)
        for s in all_settings()
    }
