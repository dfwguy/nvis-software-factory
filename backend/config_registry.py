"""Every configuration knob, declared once.

Author: Rafael M. Koike & Cursor Agent ("Ada")

A setting that is only discoverable by grepping for ``os.environ`` is a setting nobody can
document, validate, or generate an example for. So they are declared here, with a type, a default,
a description and a secrecy flag, and three things are derived from that one declaration:

* ``factory.toml.example`` -- generated by ``bin/gen-factory-example.py``, CI-checked for drift.
* the configuration reference page in the docs -- generated, so it cannot go stale.
* the startup gate's required-setting check -- so a missing value fails at boot, not at first use.

This is criterion P2 of the provenance pillar, applied to ourselves.

SECRETS ARE REFUSED FROM THE TOML FILE
--------------------------------------
A setting marked ``secret=True`` may be supplied by environment variable or by a mounted secret
file, and is rejected if it appears in ``factory.toml``. The reason is mundane: config files get
committed. Refusing the value outright, loudly, at startup, is the only version of this control
that survives contact with a hurried deployment -- a warning gets ignored, and by then the
credential is in git history.

Secret values are never echoed. ``describe()`` reports presence and length, never content.
"""

from __future__ import annotations

import os
from collections.abc import Callable
from dataclasses import dataclass, field
from typing import Any, Literal

SettingType = Literal["str", "int", "float", "bool", "path"]


@dataclass(frozen=True)
class Setting:
    """One configuration knob.

    ``env`` is the environment variable. ``section``/``key`` locate the same value in
    ``factory.toml``: ``[llm] base_url`` is ``NVSF_LLM_BASE_URL``. The mapping is spelled out
    rather than derived so an awkward name can be handled without a special case in the loader.
    """

    env: str
    section: str
    key: str
    type: SettingType
    default: str | None
    description: str
    secret: bool = False
    #: Required at startup. A callable is evaluated against the resolved environment, for settings
    #: that are only required in some modes -- OIDC credentials are required unless the mock
    #: provider is on, for instance.
    required: bool | Callable[[], bool] = False
    #: Allowed values, for documentation and for validation at startup.
    choices: tuple[str, ...] = field(default_factory=tuple)
    #: Explains a non-obvious default or interaction. Rendered into the example file as a comment.
    note: str = ""

    def is_required(self) -> bool:
        return self.required() if callable(self.required) else bool(self.required)


_REGISTRY: dict[str, Setting] = {}


def register(setting: Setting) -> Setting:
    if setting.env in _REGISTRY:
        raise RuntimeError(f"setting {setting.env} is declared twice")
    _REGISTRY[setting.env] = setting
    return setting


def all_settings() -> list[Setting]:
    """Every declared setting, ordered by TOML section then key, so generated output is stable."""
    return sorted(_REGISTRY.values(), key=lambda s: (s.section, s.key))


def sections() -> list[str]:
    seen: list[str] = []
    for setting in all_settings():
        if setting.section not in seen:
            seen.append(setting.section)
    return seen


def get(env_name: str) -> Setting | None:
    return _REGISTRY.get(env_name)


def _production() -> bool:
    return os.environ.get("NVSF_ENV", "production").lower() == "production"


def _mock_oidc_off() -> bool:
    return os.environ.get("NVSF_OIDC_MOCK", "").lower() not in {"1", "true", "yes", "on"}


